// Converts tools/octopus/out/octopus_layers.json (written by export.html) into
// main/radio_octopus_assets.h for the firmware.
//
//   node tools/octopus/gen_assets.js
//
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'out', 'octopus_layers.json'), 'utf8'));
const dst = path.join(root, 'main', 'radio_octopus_assets.h');

const W = src.width, H = src.height;
const pal = src.palette.map(p => p.rgb);
const to565 = ([r, g, b]) => ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
const swap = (v) => ((v & 0xff) << 8) | (v >> 8);
const hex4 = (v) => '0x' + v.toString(16).padStart(4, '0');
const hex2 = (v) => '0x' + v.toString(16).padStart(2, '0');

function rows(values, perLine, fmt) {
  const out = [];
  for (let i = 0; i < values.length; i += perLine) {
    out.push('    ' + values.slice(i, i + perLine).map(fmt).join(', ') + ',');
  }
  return out.join('\n');
}

const named = src.palette.map(p =>
  `constexpr uint32_t kRgb_${p.name} = 0x${p.rgb.map(c => c.toString(16).padStart(2, '0')).join('')};`);

const f = (v) => {
  const s = (+v).toFixed(4).replace(/0+$/, '').replace(/\.$/, '.0');
  return s + 'f';
};

const arms = src.arms.map((a) =>
  `    {${a.side}, ${f(a.rw)}, ${f(a.tw)}, {${a.pts.map(([x, y]) => `{${f(x)}, ${f(y)}}`).join(', ')}}},`).join('\n');
const anim = src.armAnim.map(a => `    {${f(a.phase)}, ${f(a.amp)}, ${f(a.freq)}},`).join('\n');

const body = src.body.map(i => (i < 0 ? 255 : i));

const text = `// Generated by tools/octopus/gen_assets.js from the simulator's scene renderer.
// Do not edit by hand: re-run tools/octopus/export.html, then gen_assets.js.
#pragma once

#include <cstdint>

namespace octopus_assets {

constexpr int kWidth = ${W};
constexpr int kHeight = ${H};
constexpr int kPaletteSize = ${pal.length};
constexpr uint8_t kTransparent = 255;

${named.join('\n')}

// Palette in native RGB565 (for blending) and byte-swapped for the panel.
inline constexpr uint16_t kPalette565[kPaletteSize] = {
${rows(pal.map(to565), 8, hex4)}
};
inline constexpr uint16_t kPalettePanel[kPaletteSize] = {
${rows(pal.map(c => swap(to565(c))), 8, hex4)}
};

// Static water: gradient bands, surface caustics and vignette (palette index).
inline constexpr uint8_t kBackground[kWidth * kHeight] = {
${rows(src.bg, 24, hex2)}
};

// Light beams fanning out from a point above the head. Angles are measured
// from straight down; each beam sways, pulses and breathes on its own period.
struct BeamDef {
    float angle, half_width, strength, wobble;
};
inline constexpr BeamDef kBeams[${src.beams.length}] = {
${src.beams.map(b => `    {${f(b.ang)}, ${f(b.half)}, ${f(b.str)}, ${f(b.wob)}},`).join('\n')}
};
constexpr float kBeamReach = ${f(src.reach)};  // scene px

// Mantle, head, sunglasses and arm web (palette index, kTransparent = none).
inline constexpr uint8_t kBody[kWidth * kHeight] = {
${rows(body, 24, hex2)}
};

struct ArmDef {
    int8_t side;
    float root_width;
    float tip_width;
    float pts[10][2];  // rest pose, scene px
};
struct ArmAnim {
    float phase;
    float amp;
    float freq;
};

// Outer-left to outer-right, as in the simulator.
inline constexpr ArmDef kArms[8] = {
${arms}
};
inline constexpr ArmAnim kArmAnim[8] = {
${anim}
};
inline constexpr float kSway[10] = {${src.sway.map(f).join(', ')}};

constexpr float kSparkleX = ${f(src.sparkle.x)};
constexpr float kSparkleY = ${f(src.sparkle.y)};
constexpr float kSurfaceY = ${f(7 + src.surfOff - src.row0)};
constexpr float kRaySourceX = ${f(src.anchors.cx)};
constexpr float kRaySourceY = ${f(src.anchors.mtop - 20)};

// Mantle at rest, for the gold crest glint.
constexpr float kMantleX = ${f(src.mantle.cx)};
constexpr float kMantleY = ${f(src.mantle.my)};
constexpr float kMantleW = ${f(src.mantle.mw)};
constexpr float kMantleH = ${f(src.mantle.mh)};

}  // namespace octopus_assets
`;

fs.writeFileSync(dst, text);
console.log(`wrote ${path.relative(root, dst)} (${(text.length / 1024).toFixed(0)} KB source), palette ${pal.length}`);
