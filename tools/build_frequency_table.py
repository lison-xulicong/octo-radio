#!/usr/bin/env python3
"""Compile the audited CSV frequency table into compact C++ flash data."""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

OFFSET = 1469598103934665603
PRIME = 1099511628211
PUNCTUATION = {
    "\u00b7",
    "\u2013",
    "\u2014",
    "\u3001",
    "\u3002",
    "\uff08",
    "\uff09",
    "\uff0c",
    "\uff1a",
}
FREQUENCY_METADATA = re.compile(r"(?i)(?:FM|AM)\s*[0-9][0-9.]*")


def normalize(text: str) -> str:
    text = FREQUENCY_METADATA.sub("", text)
    result = []
    for character in text:
        if character.isascii():
            if character.isalnum():
                result.append(character.lower())
        elif character not in PUNCTUATION:
            result.append(character)
    return "".join(result)


def fnv_key(city: str, station: str) -> int:
    value = OFFSET
    for data in (normalize(city), "\x1f", normalize(station)):
        for byte in data.encode("utf-8"):
            value ^= byte
            value = (value * PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--csv", default="data/fm_frequencies.csv", help="input CSV"
    )
    parser.add_argument(
        "--output",
        default="main/radio_frequency_data.h",
        help="generated C++ header",
    )
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    csv_path = root / args.csv
    output_path = root / args.output
    records: dict[int, tuple[int, str, str]] = {}

    with csv_path.open(newline="", encoding="utf-8") as source:
        for line, row in enumerate(csv.DictReader(source), start=2):
            city = row["city"].strip()
            station = row["station"].strip()
            try:
                frequency = round(float(row["fm_mhz"]) * 10)
            except ValueError:
                sys.exit(f"{csv_path}:{line}: invalid FM frequency")
            if not city or not station or not 870 <= frequency <= 1080:
                sys.exit(f"{csv_path}:{line}: invalid city/station/frequency")
            key = fnv_key(city, station)
            if not key:
                sys.exit(f"{csv_path}:{line}: empty normalized key")
            previous = records.get(key)
            if previous and previous[0] != frequency:
                sys.exit(
                    f"{csv_path}:{line}: conflicting frequencies for "
                    f"{city} / {station}"
                )
            records[key] = (frequency, city, station)

    ordered = sorted(records.items())
    lines = [
        "// Generated by tools/build_frequency_table.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "inline constexpr std::uint64_t kRadioFrequencyKeys[] = {",
    ]
    lines.extend(f"    0x{key:016x}ULL," for key, _ in ordered)
    lines.extend(
        [
            "};",
            "",
            "inline constexpr std::uint16_t kRadioFrequencyValues[] = {",
        ]
    )
    lines.extend(f"    {record[0]}," for _, record in ordered)
    lines.extend(
        [
            "};",
            "",
            f"inline constexpr std::size_t kRadioFrequencyCount = {len(ordered)};",
            "",
        ]
    )
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {output_path} with {len(ordered)} frequency records")


if __name__ == "__main__":
    main()
